"""
Report renderer — turns a ReviewReport into markdown or JSON.
"""
from __future__ import annotations

import json
from pr_sentinel.models import ReviewReport, Severity


_SEVERITY_EMOJI = {
    Severity.CRITICAL: "🔴",
    Severity.HIGH: "🟠",
    Severity.MEDIUM: "🟡",
    Severity.LOW: "🟢",
    Severity.INFO: "ℹ️ ",
}


def to_markdown(report: ReviewReport) -> str:
    lines: list[str] = []

    lines.append(f"# PR Sentinel Report")
    lines.append(f"**Repo:** `{report.repo_path}`")
    lines.append(f"**PR:** {report.pr_title or '(no title)'}")
    lines.append("")
    lines.append("## Finding Summary")
    lines.append(f"| Severity | Count |")
    lines.append(f"|----------|-------|")
    lines.append(f"| 🔴 Critical | {report.critical_count} |")
    lines.append(f"| 🟠 High     | {report.high_count} |")
    lines.append(f"| 🟡 Medium   | {report.medium_count} |")
    lines.append(f"| 🟢 Low      | {report.low_count} |")
    lines.append(f"| ℹ️  Info     | {report.info_count} |")
    lines.append(f"| **Total**  | **{report.total_findings}** |")
    lines.append("")

    # Human review prose from ReviewDrafterAgent
    if report.human_review:
        lines.append("---")
        lines.append("")
        lines.append(report.human_review)
        lines.append("")

    # Raw structured findings per agent (collapsed detail)
    lines.append("---")
    lines.append("")
    lines.append("## Structured Findings by Agent")
    for agent_result in report.agent_results:
        if agent_result.agent == "ReviewDrafterAgent":
            continue  # already shown above as human review

        lines.append(f"\n### {agent_result.agent}")
        if agent_result.error:
            lines.append(f"> ⚠️ Agent error: `{agent_result.error}`")
            continue

        # PlanAgent: render its triage plan, not findings
        if agent_result.agent == "PlanAgent":
            import json as _json
            try:
                plan = _json.loads(agent_result.raw_response)
                lines.append(f"_{plan.get('pr_summary', agent_result.summary)}_")
                if plan.get("areas_touched"):
                    lines.append("\n**Areas touched:** " + ", ".join(f"`{a}`" for a in plan["areas_touched"]))
                if plan.get("red_flags"):
                    lines.append("\n**Red flags:** " + ", ".join(plan["red_flags"]))
                if plan.get("review_focus"):
                    lines.append(f"\n**Review focus:** {plan['review_focus']}")
            except Exception:
                lines.append(f"_{agent_result.summary}_")
            continue

        lines.append(f"_{agent_result.summary}_")
        if not agent_result.findings:
            lines.append("No findings.")
            continue
        for f in agent_result.findings:
            emoji = _SEVERITY_EMOJI.get(f.severity, "")
            loc = f"`{f.file}:{f.line}`" if f.line else (f"`{f.file}`" if f.file else "")
            lines.append(f"\n**{emoji} [{f.severity.upper()}]** {f.title} {loc}")
            lines.append(f"> {f.detail}")
            if f.suggestion:
                lines.append(f"\n💡 *{f.suggestion}*")

    lines.append("")
    lines.append("---")
    lines.append("_Generated by PR Sentinel — powered by IBM Bob 2.0. All inference ran locally._")

    return "\n".join(lines)


def to_json(report: ReviewReport) -> str:
    return report.model_dump_json(indent=2)


def render(report: ReviewReport, fmt: str = "markdown") -> str:
    if fmt == "json":
        return to_json(report)
    return to_markdown(report)
